insert into public.platform_catalog_items (
  code, sku, name, description, item_type, category_name, unit_name, unit_symbol,
  default_unit_cost, default_sale_price, default_waste_percentage, active
)
select code, sku, name, description, item_type, category_name, unit_name, unit_symbol,
       unit_cost, sale_price, waste, true
from tmp_market_inputs
on conflict do nothing;

-- Insumos existentes que seguían sin precio (seed 002).
with priced as (
  update public.platform_catalog_items p
  set description = t.description,
      default_unit_cost = t.unit_cost,
      default_sale_price = t.sale_price,
      default_waste_percentage = t.waste,
      updated_at = now()
  from tmp_market_inputs t
  where p.code = t.code
    and p.default_unit_cost = 0
    and p.default_sale_price = 0
  returning p.id, p.default_unit_cost, p.default_sale_price, p.default_waste_percentage
)
insert into public.platform_catalog_price_history (
  catalog_item_id, previous_unit_cost, previous_sale_price, previous_waste_percentage,
  unit_cost, sale_price, waste_percentage, source, notes
)
select id, 0, 0, 0, default_unit_cost, default_sale_price, default_waste_percentage,
       'actualizacion_mercado_2026_11', 'Primer precio de mercado del insumo'
from priced;

